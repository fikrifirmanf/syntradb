const HEAP_ALL: &str = "SELECT count(*), count(v), sum(v), min(v), max(v) FROM bench_values";
const HEAP_ALL_PLAN: &str = "EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) SELECT count(*), count(v), sum(v), min(v), max(v) FROM bench_values";
const HEAP_RANGE: &str =
    "SELECT count(*), count(v), sum(v), min(v), max(v) FROM bench_values WHERE v BETWEEN $1 AND $2";
const HEAP_RANGE_PLAN: &str = "EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) SELECT count(*), count(v), sum(v), min(v), max(v) FROM bench_values WHERE v BETWEEN $1 AND $2";
const SEGMENT_ALL: &str = "SELECT s.rows, s.non_nulls, s.sum, s.min, s.max FROM bench_projection AS p, LATERAL syntra_segment_summary(p.segment) AS s WHERE p.name = 'dataset' LIMIT 1";
const SEGMENT_ALL_PLAN: &str = "EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) SELECT s.rows, s.non_nulls, s.sum, s.min, s.max FROM bench_projection AS p, LATERAL syntra_segment_summary(p.segment) AS s WHERE p.name = 'dataset' LIMIT 1";
const SEGMENT_RANGE: &str = "SELECT s.rows, s.non_nulls, s.sum, s.min, s.max FROM bench_projection AS p, LATERAL syntra_segment_range_summary(p.segment, $1, $2) AS s WHERE p.name = 'dataset' LIMIT 1";
const SEGMENT_RANGE_PLAN: &str = "EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) SELECT s.rows, s.non_nulls, s.sum, s.min, s.max FROM bench_projection AS p, LATERAL syntra_segment_range_summary(p.segment, $1, $2) AS s WHERE p.name = 'dataset' LIMIT 1";
const RUST_ALL: &str = "SELECT rows, non_nulls, sum, min, max FROM syntra_heap_int4_summary('bench_values','v') LIMIT 1";
const RUST_ALL_PLAN: &str = "EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) SELECT rows, non_nulls, sum, min, max FROM syntra_heap_int4_summary('bench_values','v') LIMIT 1";
const RUST_RANGE: &str = "SELECT rows, non_nulls, sum, min, max FROM syntra_heap_int4_range_summary('bench_values','v',$1,$2) LIMIT 1";
const RUST_RANGE_PLAN: &str = "EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) SELECT rows, non_nulls, sum, min, max FROM syntra_heap_int4_range_summary('bench_values','v',$1,$2) LIMIT 1";
const LIVE_ALL: &str = "SELECT rows,non_nulls,sum,min,max,route FROM syntra_live_int4_summary('bench_values','v') LIMIT 1";
const LIVE_RANGE: &str = "SELECT rows,non_nulls,sum,min,max,route FROM syntra_live_int4_range_summary('bench_values','v',$1,$2) LIMIT 1";
const CAPTURE: &str = "CREATE TABLE bench_projection AS SELECT 'dataset'::text AS name, c.segment, c.source_database, c.source_relation, c.source_schema, c.source_table, c.source_column, c.source_attribute, c.source_type, c.source_snapshot, c.source_transaction, c.source_command, c.captured_at, c.source_rows FROM syntra_capture_int4('bench_values'::regclass, 'v') AS c";
const ORDERED: &str = "INSERT INTO bench_values (id, v) SELECT n, CASE WHEN n % 17 = 0 THEN NULL ELSE n END FROM generate_series(1, $1::int4) AS n";
const SHUFFLED: &str = "INSERT INTO bench_values (id, v) SELECT n, CASE WHEN n % 17 = 0 THEN NULL ELSE n END FROM generate_series(1, $1::int4) AS n ORDER BY md5(n::text)";

struct Cluster {
    root: TempDir,
    pg_bin: PathBuf,
    running: bool,
}

fn command(command: &mut Command) -> Result<()> {
    let output = command.output()?;
    if !output.status.success() {
        return Err(std::io::Error::other(format!(
            "{} failed: {}",
            command.get_program().to_string_lossy(),
            String::from_utf8_lossy(&output.stderr)
        ))
        .into());
    }
    Ok(())
}

impl Cluster {
    fn start(pg_bin: &Path, wal_init_zero: bool) -> Result<Self> {
        // Unix socket only, in a private short path. TempDir's random name is a
        // resource identifier; benchmark data and execution order are deterministic.
        let root = tempfile::Builder::new()
            .prefix("syntra-bench-")
            .tempdir_in("/tmp")?;
        let data = root.path().join("data");
        command(
            Command::new(pg_bin.join("initdb"))
                .arg("-D")
                .arg(&data)
                .args([
                    "--username=syntra_bench",
                    "--auth=trust",
                    "--no-locale",
                    "--encoding=UTF8",
                ]),
        )?;
        // Use postgresql.conf for the socket directory instead of constructing
        // a command string. TempDir paths are generated by us, not user input.
        let socket = root.path().to_str().ok_or("socket path is not UTF-8")?;
        if socket.contains('\'') {
            return Err("invalid generated socket path".into());
        }
        use std::io::Write;
        let mut config = std::fs::OpenOptions::new()
            .append(true)
            .open(data.join("postgresql.conf"))?;
        writeln!(config, "\nlisten_addresses = ''\nunix_socket_directories = '{socket}'\nport = 28918\nmax_parallel_workers_per_gather = 0\njit = off\nstatement_timeout = '120s'\nlock_timeout = '5s'")?;
        writeln!(
            config,
            "wal_init_zero = {}",
            if wal_init_zero { "on" } else { "off" }
        )?;
        let cluster = Self {
            root,
            pg_bin: pg_bin.to_owned(),
            running: true,
        };
        let root = cluster.root_path();
        let result = command(
            Command::new(cluster.pg_bin.join("pg_ctl"))
                .arg("-D")
                .arg(root.join("data"))
                .arg("-l")
                .arg(root.join("postgres.log"))
                .args(["-w", "-t", "30", "start"]),
        );
        // Drop attempts shutdown even if startup partly succeeded.
        result?;
        Ok(cluster)
    }

    fn root_path(&self) -> &Path {
        self.root.path()
    }

    fn connect(&self, database: &str) -> Result<Client> {
        Ok(Config::new()
            .host_path(self.root_path())
            .port(28918)
            .user("syntra_bench")
            .dbname(database)
            .connect_timeout(Duration::from_secs(10))
            .connect(NoTls)?)
    }

    fn crash_restart(&mut self) -> Result<()> {
        command(
            Command::new(self.pg_bin.join("pg_ctl"))
                .arg("-D")
                .arg(self.root_path().join("data"))
                .args(["-w", "-t", "30", "stop", "-m", "immediate"]),
        )?;
        // Keep cleanup armed even if restart fails partway through startup.
        command(
            Command::new(self.pg_bin.join("pg_ctl"))
                .arg("-D")
                .arg(self.root_path().join("data"))
                .arg("-l")
                .arg(self.root_path().join("postgres.log"))
                .args(["-w", "-t", "30", "start"]),
        )
    }
}

impl Drop for Cluster {
    fn drop(&mut self) {
        if self.running {
            let status = Command::new(self.pg_bin.join("pg_ctl"))
                .arg("-D")
                .arg(self.root_path().join("data"))
                .args(["-w", "-t", "30", "stop", "-m", "fast"])
                .output();
            if !status.is_ok_and(|output| output.status.success()) {
                self.root.disable_cleanup(true);
                eprintln!(
                    "Benchmark shutdown failed; retained cluster at {}",
                    self.root.path().display()
                );
            }
        }
    }
}

fn load(client: &mut Client, rows: i32, insert: &str) -> Result<f64> {
    let start = Instant::now();
    client.batch_execute(
        "DROP TABLE IF EXISTS bench_values; CREATE TABLE bench_values (id int4 NOT NULL, v int4)",
    )?;
    client.execute(insert, &[&rows])?;
    client.batch_execute("ANALYZE bench_values")?;
    Ok(start.elapsed().as_secs_f64() * 1000.0)
}

struct Case {
    name: &'static str,
    bounds: Option<(i32, i32)>,
}

fn query(case: &Case, projection: bool, explain: bool) -> &'static str {
    match (case.bounds.is_some(), projection, explain) {
        (false, false, false) => HEAP_ALL,
        (false, false, true) => HEAP_ALL_PLAN,
        (true, false, false) => HEAP_RANGE,
        (true, false, true) => HEAP_RANGE_PLAN,
        (false, true, false) => SEGMENT_ALL,
        (false, true, true) => SEGMENT_ALL_PLAN,
        (true, true, false) => SEGMENT_RANGE,
        (true, true, true) => SEGMENT_RANGE_PLAN,
    }
}

fn rust_query(case: &Case, explain: bool) -> &'static str {
    match (case.bounds.is_some(), explain) {
        (false, false) => RUST_ALL,
        (false, true) => RUST_ALL_PLAN,
        (true, false) => RUST_RANGE,
        (true, true) => RUST_RANGE_PLAN,
    }
}

fn execute_rust(client: &mut Client, case: &Case, explain: bool) -> Result<postgres::Row> {
    let sql = rust_query(case, explain);
    if let Some((lower, upper)) = case.bounds {
        Ok(client.query_one(sql, &[&lower, &upper])?)
    } else {
        Ok(client.query_one(sql, &[])?)
    }
}

fn execute(
    client: &mut Client,
    case: &Case,
    projection: bool,
    explain: bool,
) -> Result<postgres::Row> {
    let sql = query(case, projection, explain);
    if let Some((lower, upper)) = case.bounds {
        Ok(client.query_one(sql, &[&lower, &upper])?)
    } else {
        Ok(client.query_one(sql, &[])?)
    }
}

fn run_case(
    plain: &mut Client,
    enabled: &mut Client,
    case: &Case,
    repetitions: usize,
) -> Result<Value> {
    let expected = correctness_values(&execute(plain, case, false, false)?)?;
    let heap = correctness_values(&execute(enabled, case, false, false)?)?;
    let projection = correctness_values(&execute(enabled, case, true, false)?)?;
    let rust_heap = correctness_values(&execute_rust(enabled, case, false)?)?;
    if expected != heap || expected != projection || expected != rust_heap {
        return Err("result mismatch; refusing to report timings".into());
    }
    let counters_sql = if case.bounds.is_some() {
        "SELECT json_build_object('groups_scanned', s.groups_scanned, 'groups_pruned', s.groups_pruned, 'rows_examined', s.rows_examined, 'scan_bytes', s.scan_bytes, 'validation_bytes', s.validation_bytes) FROM bench_projection AS p, LATERAL syntra_segment_range_summary(p.segment, $1, $2) AS s WHERE p.name = 'dataset' LIMIT 1"
    } else {
        "SELECT json_build_object('groups_scanned', s.groups_scanned, 'groups_pruned', s.groups_pruned, 'rows_examined', s.rows_examined, 'scan_bytes', s.scan_bytes, 'validation_bytes', s.validation_bytes) FROM bench_projection AS p, LATERAL syntra_segment_summary(p.segment) AS s WHERE p.name = 'dataset' LIMIT 1"
    };
    let counters: Value = if let Some((lower, upper)) = case.bounds {
        enabled
            .query_one(counters_sql, &[&lower, &upper])?
            .try_get(0)?
    } else {
        enabled.query_one(counters_sql, &[])?.try_get(0)?
    };
    let mut samples: [Vec<Sample>; 4] = Default::default();
    let mut plans: [Value; 4] = Default::default();
    // Every route gets one warmup. Rotate the first route deterministically per
    // repetition so one implementation is not always measured first.
    for round in 0..=repetitions {
        for step in 0..4 {
            let route = (round + step) % 4;
            let row = match route {
                0 => execute(plain, case, false, true)?,
                1 => execute(enabled, case, false, true)?,
                2 => execute(enabled, case, true, true)?,
                _ => execute_rust(enabled, case, true)?,
            };
            let plan: Value = row.try_get(0)?;
            let sample = Sample::from_explain(&plan)?;
            if round != 0 {
                samples[route].push(sample);
            }
            plans[route] = plan;
        }
    }
    let plain_report = summarize_samples(&samples[0])?;
    let heap_report = summarize_samples(&samples[1])?;
    let projection_report = summarize_samples(&samples[2])?;
    let rust_report = summarize_samples(&samples[3])?;
    // Normal prepared requests complement EXPLAIN: native per-tuple executor
    // instrumentation has a different cost from an opaque C function scan.
    let statements = [
        plain.prepare(query(case, false, false))?,
        enabled.prepare(query(case, false, false))?,
        enabled.prepare(query(case, true, false))?,
        enabled.prepare(rust_query(case, false))?,
        enabled.prepare(if case.bounds.is_some() {
            LIVE_RANGE
        } else {
            LIVE_ALL
        })?,
    ];
    let mut requests: [Vec<f64>; 5] = Default::default();
    // unslop-ignore N_PLUS_ONE_IN_LOOP -- Each iteration measures an independent prepared request; batching would change its latency.
    for round in 0..=repetitions {
        // unslop-ignore N_PLUS_ONE_IN_LOOP -- Rotate independent benchmark routes, not per-record database lookups.
        for step in 0..5 {
            let route = (round + step) % 5;
            let client = if route == 0 {
                &mut *plain
            } else {
                &mut *enabled
            };
            let start = Instant::now();
            let row = if let Some((lower, upper)) = case.bounds {
                client.query_one(&statements[route], &[&lower, &upper])?
            } else {
                client.query_one(&statements[route], &[])?
            };
            let elapsed = start.elapsed().as_secs_f64() * 1000.0;
            if correctness_values(&row)? != expected {
                return Err("prepared aggregate result mismatch; refusing timings".into());
            }
            if route == 4 && row.try_get::<_, &str>(5)? != "projection" {
                return Err("trusted benchmark did not reuse its published projection".into());
            }
            if round != 0 {
                requests[route].push(elapsed);
            }
        }
    }
    Ok(
        json!({ "name": case.name, "bounds": case.bounds, "correctness": "matched",
            "expected": { "rows": expected.0, "non_nulls": expected.1, "sum": expected.2, "min": expected.3, "max": expected.4 },
        "sql": { "heap": query(case, false, false), "projection": query(case, true, false), "rust_heap": rust_query(case, false) }, "projection_counters": counters,
            "postgresql": plain_report, "enabled_heap": heap_report, "projection": projection_report, "rust_heap": rust_report,
            "prepared_request_samples_ms": { "postgresql": requests[0], "enabled_heap": requests[1], "projection": requests[2], "rust_heap": requests[3], "trusted_live": requests[4] },
            "prepared_request_scope": "client roundtrip; one warmup then rotated routes; correctness checked after every timed request; no EXPLAIN instrumentation",
            "last_plans": { "postgresql": plans[0], "enabled_heap": plans[1], "projection": plans[2], "rust_heap": plans[3] },
        }),
    )
}

fn run(options: &Options) -> Result<Value> {
    let mut cluster = Cluster::start(&options.pg_bin, options.wal_init_zero)?;
    let mut admin = cluster.connect("postgres")?;
    admin.batch_execute("CREATE DATABASE syntra_plain TEMPLATE template0")?;
    admin.batch_execute("CREATE DATABASE syntra_enabled TEMPLATE template0")?;
    let mut plain = cluster.connect("syntra_plain")?;
    let mut enabled = cluster.connect("syntra_enabled")?;
    enabled.batch_execute("CREATE EXTENSION syntradb")?;
    // Ensure the heap-overhead path has actually loaded the Rust library/hook.
    let extension_version: String = enabled
        .query_one("SELECT syntra_version()", &[])?
        .try_get(0)?;
    let extension_profile: String = enabled
        .query_one("SELECT syntra_build_profile()", &[])?
        .try_get(0)?;
    let extension_source_fingerprint: String = enabled
        .query_one("SELECT syntra_source_fingerprint()", &[])?
        .try_get(0)?;
    let runner_source_fingerprint = env!("SYNTRA_SOURCE_FINGERPRINT");
    syntra_bench::verify_source_fingerprints(
        &extension_source_fingerprint,
        runner_source_fingerprint,
    )?;
    let snapshot_checks = checks::snapshot_checks(&cluster, &mut enabled)?;
    let mut trusted_checks = trusted_checks::run(&cluster)?;
    trusted_checks.extend(trusted_checks::run_captured(&cluster)?);
    let capture_checks = capture_checks::run(&cluster)?;
    let checkpoint_checks = checkpoint_checks::run(&cluster)?;
    let tail_checks = tail_checks::run(&cluster)?;
    let server: String = plain.query_one("SELECT version()", &[])?.try_get(0)?;
    let settings: Value = plain.query_one(r#"SELECT json_build_object(
        'shared_buffers', current_setting('shared_buffers'), 'work_mem', current_setting('work_mem'),
        'jit', current_setting('jit'), 'max_parallel_workers_per_gather', current_setting('max_parallel_workers_per_gather'),
        'fsync', current_setting('fsync'), 'server_encoding', current_setting('server_encoding'),
        'debug_assertions', current_setting('debug_assertions'),
        'synchronous_commit', current_setting('synchronous_commit'),
        'full_page_writes', current_setting('full_page_writes'),
        'wal_init_zero', current_setting('wal_init_zero'), 'wal_recycle', current_setting('wal_recycle'),
        'wal_sync_method', current_setting('wal_sync_method'))"#, &[])?.try_get(0)?;
    if options.require_production {
        syntra_bench::production_guard(&settings, &extension_profile, !cfg!(debug_assertions))?;
    }
    let mut datasets = Vec::new();
    for (layout, insert) in [("ordered", ORDERED), ("shuffled_md5", SHUFFLED)] {
        eprintln!(
            "Benchmarking {layout}: {} rows, {} samples per route/case",
            options.rows, options.repetitions
        );
        let plain_load = load(&mut plain, options.rows, insert)?;
        let enabled_load = load(&mut enabled, options.rows, insert)?;
        enabled.batch_execute("DROP TABLE IF EXISTS bench_projection")?;
        let build = Instant::now();
        enabled.batch_execute(CAPTURE)?;
        let build_ms = build.elapsed().as_secs_f64() * 1000.0;
        enabled.batch_execute(
            "ALTER TABLE bench_projection ADD PRIMARY KEY (name); ANALYZE bench_projection",
        )?;
        let tracking_start = Instant::now();
        enabled.query_one("SELECT syntra_track_source('bench_values','v')", &[])?;
        let tracking_setup_ms = tracking_start.elapsed().as_secs_f64() * 1000.0;
        let publication_start = Instant::now();
        let published: i64 = enabled
            .query_one(
                "SELECT syntra_publish_trusted_int4('bench_values','v')",
                &[],
            )?
            .try_get(0)?;
        let trusted_publication_ms = publication_start.elapsed().as_secs_f64() * 1000.0;
        if published != i64::from(options.rows) {
            return Err("trusted benchmark publication row count mismatch".into());
        }
        let heap_bytes: i64 = plain
            .query_one(
                "SELECT pg_total_relation_size('bench_values'::regclass)",
                &[],
            )?
            .try_get(0)?;
        let projection_bytes: i64 = enabled
            .query_one(
                "SELECT pg_total_relation_size('bench_projection'::regclass)",
                &[],
            )?
            .try_get(0)?;
        let encoded_bytes: i32 = enabled
            .query_one(
                "SELECT octet_length(segment) FROM bench_projection WHERE name = 'dataset' LIMIT 1",
                &[],
            )?
            .try_get(0)?;
        let center = (options.rows / 2).max(1);
        let cases = [
            Case {
                name: "all",
                bounds: None,
            },
            Case {
                name: "range_10_percent",
                bounds: Some((center, center + (options.rows / 10).max(1) - 1)),
            },
            Case {
                name: "range_0_1_percent",
                bounds: Some((center, center + (options.rows / 1000).max(1) - 1)),
            },
        ];
        let reports = cases
            .iter()
            .map(|case| run_case(&mut plain, &mut enabled, case, options.repetitions))
            .collect::<Result<Vec<_>>>()?;
        // unslop-ignore N_PLUS_ONE_IN_LOOP -- Repeated captures measure independent requests; batching changes this benchmark.
        let mut capture_samples_ms = Vec::with_capacity(options.repetitions);
        let capture = enabled.prepare("SELECT source_rows, octet_length(segment) FROM syntra_capture_int4('bench_values'::regclass, 'v') LIMIT 1")?;
        for _ in 0..options.repetitions {
            let start = Instant::now();
            let row = enabled.query_one(&capture, &[])?;
            let elapsed = start.elapsed().as_secs_f64() * 1000.0;
            let captured_rows: i64 = row.try_get(0)?;
            let captured_bytes: i32 = row.try_get(1)?;
            if captured_rows != i64::from(options.rows) || captured_bytes != encoded_bytes {
                return Err("capture cost probe returned inconsistent dimensions".into());
            }
            capture_samples_ms.push(elapsed);
        }
        datasets.push(json!({ "layout": layout, "insert_sql": insert, "rows": options.rows,
            "plain_load_ms": plain_load, "enabled_load_ms": enabled_load, "projection_build_with_ddl_ms": build_ms,
            "tracking_setup_ms": tracking_setup_ms, "trusted_publication_ms": trusted_publication_ms,
            "heap_total_bytes": heap_bytes, "projection_total_bytes": projection_bytes,
            "encoded_segment_bytes": encoded_bytes, "cases": reports,
            "source_capture_request_samples_ms": capture_samples_ms }));
    }
    let mixed = if options.mixed_seconds > 0 {
        mixed::run(&cluster, options)?
    } else {
        Value::Null
    };
    let recovery = if options.recovery_checks {
        checks::recovery_checks(&mut cluster)?
    } else {
        Value::Null
    };
    let trusted_stress = if options.trusted_stress_seconds > 0 {
        trusted_stress::run(&cluster, options)?
    } else {
        Value::Null
    };
    let capture_recovery = if options.recovery_checks {
        capture_checks::recovery(&mut cluster)?
    } else {
        Value::Null
    };
    let checkpoint_recovery = if options.recovery_checks {
        checkpoint_checks::recovery(&mut cluster)?
    } else {
        Value::Null
    };
    let checkpoint_stress =
        if options.checkpoint_stress_seconds > 0 || options.checkpoint_soak_seconds > 0 {
            checkpoint_stress::run(&cluster, options).inspect_err(|_| {
                // The cluster directory is removed on drop; keep the server's
                // account of the failure in the run's output.
                let log = std::fs::read_to_string(cluster.root_path().join("postgres.log"))
                    .unwrap_or_default();
                let lines: Vec<&str> = log.lines().collect();
                eprintln!("PostgreSQL log, last {} lines:", lines.len().min(60));
                for line in &lines[lines.len().saturating_sub(60)..] {
                    eprintln!("  {line}");
                }
            })?
        } else {
            Value::Null
        };
    let refresh_costs = if options.refresh_cost_checks {
        refresh_costs::run(&cluster, options)?
    } else {
        Value::Null
    };
    let catalog_probe = if options.catalog_probe_checks {
        catalog_probe::run(&cluster, options)?
    } else {
        Value::Null
    };
    let configure = Command::new(options.pg_bin.join("pg_config"))
        .arg("--configure")
        .output()?;
    if !configure.status.success() {
        return Err("cannot read PostgreSQL build configuration".into());
    }
    Ok(
        json!({ "format_version": 1, "runner_version": env!("CARGO_PKG_VERSION"),
        "extension_version": extension_version, "extension_profile": extension_profile,
        "source_fingerprint_schema": 1, "extension_source_fingerprint": extension_source_fingerprint,
        "runner_source_fingerprint": runner_source_fingerprint,
        "runner_profile": if cfg!(debug_assertions) { "debug" } else { "release" },
        "snapshot_checks": snapshot_checks, "trusted_checks": trusted_checks, "capture_checks": capture_checks, "checkpoint_checks": checkpoint_checks, "tail_checks": tail_checks, "postgresql": server,
        "postgresql_configure": String::from_utf8_lossy(&configure.stdout).trim(),
        "os": std::env::consts::OS, "architecture": std::env::consts::ARCH,
        "logical_cpus": std::thread::available_parallelism()?.get(), "settings": settings,
        "cache_mode": "warm; one warmup per case/route", "repetitions": options.repetitions,
        "execution_order": "four EXPLAIN routes and five prepared-request routes rotated deterministically each repetition",
        "timing": "server EXPLAIN ANALYZE execution time; client and planning latency excluded",
        "scope": "warm data; isolated analytical cases plus optional paced mixed microbenchmark; no cold-cache, full HTAP synchronization or ClickHouse comparison",
        "datasets": datasets, "mixed": mixed, "recovery_checks": recovery, "capture_recovery": capture_recovery, "checkpoint_recovery": checkpoint_recovery, "trusted_stress": trusted_stress, "checkpoint_stress": checkpoint_stress, "refresh_costs": refresh_costs, "catalog_probe": catalog_probe }),
    )
}

fn main() -> Result<()> {
    let options = Options::parse(std::env::args().skip(1))?;
    let report = run(&options)?;
    if let Some(parent) = options
        .output
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
    {
        std::fs::create_dir_all(parent)?;
    }
    let temporary = tempfile::NamedTempFile::new_in(
        options
            .output
            .parent()
            .filter(|p| !p.as_os_str().is_empty())
            .unwrap_or(Path::new(".")),
    )?;
    serde_json::to_writer_pretty(&temporary, &report)?;
    temporary.as_file().sync_all()?;
    temporary.persist(&options.output)?;
    eprintln!("Wrote {}", options.output.display());
    Ok(())
}
